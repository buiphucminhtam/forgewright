#!/usr/bin/env python3
"""Finite prevention recipe; records only checks actually executed by this PID."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "scripts/runtime"), str(ROOT / "scripts/hooks"),
                str(ROOT / "scripts/lite")]
from host_job_profiles import install_profile, load_profile, ProfileError
from project_disk import report_project
from resource_admission import explicit_profile
from evidence_common import execution_manifest, schema_errors, sha256_text, worktree_fingerprint

REF = "tests/runtime/resource_prevention.py"
CLAIMS = {
    "source-preflight": "Reviewed finite recipes reject changed source inputs",
    "disk-preflight": "Incomplete project census reports UNVERIFIED without a byte total",
    "literal-preflight": "Only an exact single-line profile invocation selects a recipe",
}
NEGATIVE = "Changed sources and compound commands are rejected; incomplete census has no verified total"


def observed_command():
    # The original launcher spelling is part of the canonical job argv hash.
    # sys.executable may point at another Homebrew symlink to the same binary.
    return list(sys.orig_argv)


def checks():
    observed = []
    with tempfile.TemporaryDirectory(prefix="prevention-") as folder:
        base = Path(folder)
        root = base / "project"; root.mkdir()
        script = root / "build.py"; script.write_text('print("finite")\n')
        home = base / "profiles"; home.mkdir(mode=0o700)
        profile = {
            "schema": "forgewright-finite-profile/v2", "id": "preflight-v1",
            "project": str(root), "cwd": ".", "argv": [sys.executable, str(script)],
            "command": "python build.py", "memory_mib": 128, "scratch_bytes": 0,
            "disk_floor_bytes": 0, "timeout": 10,
            "sources": {"build.py": hashlib.sha256(script.read_bytes()).hexdigest()}, "env": {},
            "artifact_policy": {"schema": "forgewright-artifact-policy/v1",
                "scratch_limit_bytes": 4096, "output_limit_bytes": 4096,
                "retained_limit_bytes": 8192, "retain_generations": 2,
                "ttl_seconds": 3600, "project_limit_bytes": 16 * 1024**2},
            "disk_paths": [{"path": str(root), "device": root.stat().st_dev}],
        }
        expected = install_profile(home, profile)
        assert load_profile(home, root, profile["id"], expected)["id"] == profile["id"]
        script.write_text('print("changed")\n')
        try:
            load_profile(home, root, profile["id"], expected)
        except ProfileError:
            observed.append("source-preflight: unchanged accepted; changed source rejected")
        else:
            raise AssertionError("changed source admitted")
        for name in ("one.bin", "two.bin", "three.bin"):
            (root / name).write_bytes(b"x" * 128)
        complete = report_project(root, host_budget=base / "absent")
        partial = report_project(root, host_budget=base / "absent", max_entries=1)
        assert complete["complete"] and complete["total_bytes"] >= 384
        assert not partial["complete"] and partial["total_bytes"] is None
        assert partial["verdict"] == "UNVERIFIED"
        observed.append("disk-preflight: generated bytes counted; partial census rejected")
        enrollment = {"profiles": {profile["id"]: expected}}
        command = "forge delegate exec --profile " + profile["id"] + " --digest " + expected
        assert explicit_profile(command, enrollment) == profile["id"]
        for invalid in (command + ";id", command.replace(" --profile", "\n--profile"),
                        command.replace(expected, "0" * 64)):
            assert explicit_profile(invalid, enrollment) is None
        observed.append("literal-preflight: exact invocation accepted; operators/newline/digest mismatch rejected")
    return "\n".join(observed) + "\n"


def main():
    if sys.flags.optimize:
        raise SystemExit("Optimized Python cannot execute acceptance assertions")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tier", required=True, choices=("contract", "runtime", "e2e"))
    parser.add_argument("--turn", required=True)
    parser.add_argument("--review-ref", required=True)
    args = parser.parse_args()
    assert ROOT == Path.cwd().resolve()
    assert Path(args.turn).name == args.turn and args.turn not in (".", "..")
    output = checks()
    command = observed_command()
    execution, errors = execution_manifest(ROOT, command, [REF])
    assert not errors, errors
    evidence = {
        "schema_version": "2", "turn": args.turn,
        "acceptance_criteria": [{"id": key, "claim": claim, "test_refs": [REF]}
                                for key, claim in CLAIMS.items()],
        "command": command, "execution": execution, "tier": args.tier, "test_refs": [REF],
        "negative_paths": [NEGATIVE], "negative_path_bindings": [{"id": "invalid-preconditions",
            "claim": NEGATIVE, "acceptance_ids": list(CLAIMS), "test_refs": [REF]}],
        "limitations": ["Synthetic rejection inputs; no claim of application correctness or same-user identity authentication"],
        "change_kind": "feature", "phase": "verification", "risk": "hard" if args.tier == "runtime" else "standard",
        "implementer_id": "codex-parent-resource-rollout",
        "reviewer": {"id": "astra-curie-independent", "status": "pending",
                     "evidence_ref": args.review_ref} if args.tier == "runtime" else {"status": "not_required"},
        "exit_code": 0, "output": output, "output_sha256": sha256_text(output),
        "output_truncated": False, "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "workspace": str(ROOT), "tree_sha": worktree_fingerprint(ROOT),
    }
    if args.tier == "runtime":
        evidence["links"] = {tier: "resource-rollout-completion/prevention-" + tier + ".json"
                             for tier in ("contract", "e2e")}
    assert not schema_errors(evidence), schema_errors(evidence)
    from resource_enrollment import atomic_private
    path = ROOT / ".forgewright/verify/resource-rollout-completion" / (args.turn + ".json")
    atomic_private(path, (json.dumps(evidence, indent=2) + "\n").encode())
    print(output, end="")


if __name__ == "__main__":
    main()
